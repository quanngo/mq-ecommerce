#!/usr/bin/env bash
# Launches workspace projects under PM2.
#   ./start.sh              start every project
#   ./start.sh frontend     start only frontend projects
#   ./start.sh backend      start only backend projects
#   ./start.sh <key>        start a single project (key from projects.env)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/lib.sh
source "$SCRIPT_DIR/scripts/lib.sh"

ensure_pm2() {
  if command -v pm2 >/dev/null 2>&1; then
    return
  fi

  echo "pm2 is not installed. This project uses PM2 to run and manage all services."
  echo "Install it globally with: npm install -g pm2"
  read -r -p "Install pm2 now? [y/N] " reply
  case "$reply" in
    [yY][eE][sS]|[yY])
      npm install -g pm2
      ;;
    *)
      echo "Aborting. Install pm2 manually (npm install -g pm2) then re-run ./start.sh." >&2
      exit 1
      ;;
  esac
}

ALL_KEYS=()
ALL_TYPES=()
FRONTEND_KEYS=()
BACKEND_KEYS=()

collect_key() {
  local key="$1" _name="$2" _repo="$3" _start="$4" type_lower="$5"
  ALL_KEYS+=("$key")
  ALL_TYPES+=("$type_lower")
  if [[ "$type_lower" == "frontend" ]]; then
    FRONTEND_KEYS+=("$key")
  else
    BACKEND_KEYS+=("$key")
  fi
}

write_ecosystem_entry() {
  local key="$1" _name="$2" _repo="$3" start="$4" type_lower="$5"
  local dir
  dir="$(project_dir "$type_lower" "$key")"
  local escaped_start="${start//\"/\\\"}"
  cat >>"$ECOSYSTEM_FILE" <<EOF
    {
      name: "${key}",
      cwd: "${dir}",
      script: "bash",
      args: ["-c", "${escaped_start}"],
    },
EOF
}

generate_ecosystem() {
  ECOSYSTEM_FILE="$ROOT_DIR/ecosystem.config.js"
  {
    echo "// Auto-generated by start.sh from projects.env. Do not edit by hand."
    echo "module.exports = {"
    echo "  apps: ["
  } >"$ECOSYSTEM_FILE"

  for_each_project FRONTEND write_ecosystem_entry
  for_each_project BACKEND write_ecosystem_entry

  {
    echo "  ],"
    echo "};"
  } >>"$ECOSYSTEM_FILE"
}

join_by_comma() {
  local IFS=,
  echo "$*"
}

usage_footer() {
  echo
  echo "Useful PM2 commands:"
  echo "  pm2 list             # show running processes"
  echo "  pm2 logs [key]       # tail logs (all, or one project)"
  echo "  pm2 restart <key>    # restart a project"
  echo "  pm2 stop all         # stop everything"
  echo "  pm2 delete all       # remove all processes from pm2"
}

ensure_pm2
load_projects
for_each_project FRONTEND collect_key
for_each_project BACKEND collect_key
generate_ecosystem

TARGET="${1:-}"

case "$TARGET" in
  "")
    pm2 start "$ECOSYSTEM_FILE"
    ;;
  frontend)
    if [[ ${#FRONTEND_KEYS[@]} -eq 0 ]]; then
      echo "no frontend projects defined in projects.env" >&2
      exit 1
    fi
    pm2 start "$ECOSYSTEM_FILE" --only "$(join_by_comma "${FRONTEND_KEYS[@]}")"
    ;;
  backend)
    if [[ ${#BACKEND_KEYS[@]} -eq 0 ]]; then
      echo "no backend projects defined in projects.env" >&2
      exit 1
    fi
    pm2 start "$ECOSYSTEM_FILE" --only "$(join_by_comma "${BACKEND_KEYS[@]}")"
    ;;
  *)
    found=0
    for k in "${ALL_KEYS[@]}"; do
      [[ "$k" == "$TARGET" ]] && found=1 && break
    done
    if [[ "$found" -eq 0 ]]; then
      echo "error: unknown project key '$TARGET'" >&2
      echo "valid keys: $(join_by_comma "${ALL_KEYS[@]}")" >&2
      exit 1
    fi
    pm2 start "$ECOSYSTEM_FILE" --only "$TARGET"
    ;;
esac

usage_footer
